#!/usr/bin/env python3
"""Generate compile_large.ls, a big straight-line lsaca program used only to
measure cold compile time as a function of program size.

The generated file is checked in next to this script. Re-run this script to
regenerate it; the output is deterministic (no timestamps).

Usage: python benchmarks/programs/gen_compile_large.py
"""

from pathlib import Path

N_FUNCS = 450
OUT_NAME = "compile_large.ls"


def function_lines(index: int) -> list:
    name = f"compute_{index:03d}"
    lines = [
        f"fn {name}(x: i64) -> i64 {{",
        "    let a = x * 3 + 7;",
        "    let b = a * 5 - 11;",
        "    let c = b + a * 2;",
        "    let d = c * 3 - b;",
        "    let e = d + c - a;",
        "    e",
        "}",
        "",
    ]
    return lines


def main() -> None:
    lines = [
        "// compile_large: GENERATED FILE - do not edit by hand.",
        f"// Generated by gen_compile_large.py: {N_FUNCS} small straight-line functions",
        "// plus a main that calls each one. This program exists to measure how the",
        "// lsaca cold build time scales with program size; it is a compile-only",
        "// workload in scripts/bench.py (it is never timed at run time).",
        "",
    ]
    for index in range(N_FUNCS):
        lines.extend(function_lines(index))

    lines.append("fn main() {")
    lines.append("    let mut acc: i64 = 1;")
    for index in range(N_FUNCS):
        # Keep the accumulator bounded: the generated program is still valid to
        # run (it is only *timed* at compile time), but must not overflow i64.
        lines.append(
            f"    acc = (acc + compute_{index:03d}(acc % 1000)) % 1000000007;"
        )
    lines.append('    println!("checksum={}", acc);')
    lines.append("}")
    lines.append("")

    text = "\n".join(lines)
    out_path = Path(__file__).resolve().parent / OUT_NAME
    out_path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out_path} ({len(lines)} lines, {len(text)} bytes)")


if __name__ == "__main__":
    main()
