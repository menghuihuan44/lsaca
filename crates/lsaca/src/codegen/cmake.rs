//! CMakeLists.txt generation for the emitted C project.
//!
//! The generated project is deliberately boring: one executable built from
//! main.c and the runtime, C17, with a Debug/Release profile split. It uses no
//! CMake variables that need the project directory substituted in, which keeps
//! the output deterministic and free of path escaping issues.

/// Name of the executable / CMake target.
pub fn target_name(program_name: &str, fallback: &str) -> String {
    let raw = if program_name.trim().is_empty() {
        fallback
    } else {
        program_name
    };
    let cleaned = crate::codegen::util::sanitize_ident(raw);
    if cleaned.trim_matches('_').is_empty() {
        String::from("lsaca_program")
    } else {
        cleaned
    }
}

/// Render the CMakeLists.txt for a generated project.
pub fn render(program_name: &str, fallback: &str) -> String {
    let name = target_name(program_name, fallback);
    let mut out = String::new();
    out.push_str("# Generated by the lsaca compiler. Do not edit.\n");
    out.push_str("cmake_minimum_required(VERSION 3.16)\n");
    out.push_str(&format!("project({} C)\n", name));
    out.push('\n');
    out.push_str("set(CMAKE_C_STANDARD 17)\n");
    out.push_str("set(CMAKE_C_STANDARD_REQUIRED ON)\n");
    out.push_str("set(CMAKE_C_EXTENSIONS OFF)\n");
    out.push('\n');
    out.push_str("option(LSACA_SANITIZE \"Build with AddressSanitizer and UBSan\" OFF)\n");
    out.push('\n');
    out.push_str(&format!("add_executable({0} main.c lsaca_rt.c)\n", name));
    out.push('\n');
    out.push_str("if(CMAKE_C_COMPILER_ID MATCHES \"GNU|Clang\")\n");
    out.push_str(&format!(
        "  target_compile_options({} PRIVATE -Wall -Wextra)\n",
        name
    ));
    out.push_str("endif()\n");
    out.push('\n');
    out.push_str(&format!(
        "target_compile_options({0} PRIVATE $<$<CONFIG:Debug>:-g;-O0;-DLSACA_DEBUG> $<$<CONFIG:Release>:-O2;-DNDEBUG>)\n",
        name
    ));
    out.push('\n');
    out.push_str("if(LSACA_SANITIZE)\n");
    out.push_str(&format!(
        "  target_compile_options({0} PRIVATE -fsanitize=address,undefined -fno-omit-frame-pointer)\n",
        name
    ));
    out.push_str(&format!(
        "  target_link_options({0} PRIVATE -fsanitize=address,undefined)\n",
        name
    ));
    out.push_str("endif()\n");
    out.push_str("if(UNIX AND NOT APPLE)\n");
    out.push_str(&format!("  target_link_libraries({} PRIVATE m)\n", name));
    out.push_str("endif()\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_a_deterministic_project() {
        let text = render("hello", "program");
        assert!(text.contains("project(hello C)"));
        assert!(text.contains("add_executable(hello main.c lsaca_rt.c)"));
        assert!(text.contains("CMAKE_C_STANDARD 17"));
        assert!(text.contains("CONFIG:Debug"));
        assert!(text.contains("CONFIG:Release"));
        assert!(text.contains("LSACA_SANITIZE"));
        assert!(text.contains("if(UNIX AND NOT APPLE)"));
        assert!(text.contains("target_link_libraries(hello PRIVATE m)"));
        assert_eq!(text, render("hello", "program"));
    }

    #[test]
    fn sanitizes_names() {
        assert_eq!(target_name("", "my prog"), "my_prog");
        assert_eq!(target_name("2cool", "x"), "_2cool");
        assert_eq!(target_name("  ", "x"), "x");
        assert_eq!(target_name("   ", "   "), "lsaca_program");
    }
}
