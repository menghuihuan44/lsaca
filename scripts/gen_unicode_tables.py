#!/usr/bin/env python3
"""Generate runtime/lsaca_rt_unicode.c, the Unicode tables for the lsaca runtime.

The generated file contains:
  * full Unicode default case mappings (upper and lower) used by
    String.to_uppercase() / String.to_lowercase(); one scalar can expand to
    several scalars (for example U+00DF -> "SS", U+0130 -> "i" + U+0307);
  * the Unicode White_Space set used by String.trim();
  * the set of scalars that Rust Debug formatting escapes as \\u{...}
    (categories Cc, Cf, Cs, Co, Cn, Zl, Zp and every mark category M*).

The data comes from Python's built-in unicodedata module only (no third party
packages).  Output is deterministic for a given Python version: re-running the
generator with the same Python must leave runtime/lsaca_rt_unicode.c unchanged.

Usage (from the repository root):
    python3 scripts/gen_unicode_tables.py

The script prints a short summary to stdout.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

MAX_SCALAR = 0x10FFFF
SURROGATE_FIRST = 0xD800
SURROGATE_LAST = 0xDFFF
MAX_EXPANSION = 4

# Unicode White_Space property (U+0009..U+000D, U+0020, U+0085, U+00A0,
# U+1680, U+2000..U+200A, U+2028, U+2029, U+202F, U+205F, U+3000).
WHITE_SPACE_RANGES = [
    (0x0009, 0x000D),
    (0x0020, 0x0020),
    (0x0085, 0x0085),
    (0x00A0, 0x00A0),
    (0x1680, 0x1680),
    (0x2000, 0x200A),
    (0x2028, 0x2029),
    (0x202F, 0x202F),
    (0x205F, 0x205F),
    (0x3000, 0x3000),
]

# Categories whose scalars Rust escape_debug renders as \\u{...}.
ESCAPE_CATEGORIES = {"Cc", "Cf", "Cs", "Co", "Cn", "Zl", "Zp"}


def is_scalar_value(value: int) -> bool:
    return 0 <= value <= MAX_SCALAR and not (SURROGATE_FIRST <= value <= SURROGATE_LAST)


def build_case_table(mapping: str):
    """Return (entries, data) for one case mapping direction.

    entries is a list of (codepoint, data_offset, expansion_length); data is the
    flat list of mapped scalars.
    """
    entries = []
    data = []
    for cp in range(MAX_SCALAR + 1):
        source = chr(cp)
        mapped = source.upper() if mapping == "upper" else source.lower()
        values = [ord(ch) for ch in mapped]
        if len(values) == 1 and values[0] == cp:
            continue
        if len(values) > MAX_EXPANSION:
            raise SystemExit(
                "case mapping for U+%04X expands to %d scalars, more than the "
                "runtime supports (%d)" % (cp, len(values), MAX_EXPANSION)
            )
        for value in values:
            if not is_scalar_value(value):
                raise SystemExit("case mapping for U+%04X produced invalid scalar U+%04X" % (cp, value))
        entries.append((cp, len(data), len(values)))
        data.extend(values)
    return entries, data


def escape_ranges():
    ranges = []
    start = None
    for cp in range(MAX_SCALAR + 1):
        category = unicodedata.category(chr(cp))
        escape = category in ESCAPE_CATEGORIES or category.startswith("M")
        if escape and start is None:
            start = cp
        elif not escape and start is not None:
            ranges.append((start, cp - 1))
            start = None
    if start is not None:
        ranges.append((start, MAX_SCALAR))
    return ranges


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    output = repo_root / "runtime" / "lsaca_rt_unicode.c"

    upper_entries, upper_data = build_case_table("upper")
    lower_entries, lower_data = build_case_table("lower")
    escapes = escape_ranges()

    lines = []
    lines.append("/*")
    lines.append(" * Generated by scripts/gen_unicode_tables.py -- do not edit by hand.")
    lines.append(" *")
    lines.append(" * Unicode version: %s (Python unicodedata)" % unicodedata.unidata_version)
    lines.append(" * Regenerate with: python3 scripts/gen_unicode_tables.py")
    lines.append(" *")
    lines.append(" * The tables drive String.to_uppercase(), String.to_lowercase(),")
    lines.append(" * String.trim() and the Debug escaping predicate of the lsaca runtime.")
    lines.append(" */")
    lines.append("")
    lines.append('#include "lsaca_rt_unicode.h"')
    lines.append("")
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    lines.append("")

    # Case mapping tables.
    lines.append("struct ls_rt_case_entry {")
    lines.append("    uint32_t ch;")
    lines.append("    uint32_t offset;")
    lines.append("    uint8_t length;")
    lines.append("};")
    lines.append("")
    for prefix, entries, data in (
        ("upper", upper_entries, upper_data),
        ("lower", lower_entries, lower_data),
    ):
        lines.append("static const struct ls_rt_case_entry ls_rt_unicode_%s_map[] = {" % prefix)
        for ch, offset, length in entries:
            lines.append("    {0x%Xu, %uu, %uu}," % (ch, offset, length))
        lines.append("};")
        lines.append("")
        lines.append("static const uint32_t ls_rt_unicode_%s_data[] = {" % prefix)
        for index in range(0, len(data), 12):
            chunk = data[index:index + 12]
            lines.append("    " + ", ".join("0x%Xu" % value for value in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append("struct ls_rt_codepoint_range {")
    lines.append("    uint32_t first;")
    lines.append("    uint32_t last;")
    lines.append("};")
    lines.append("")

    lines.append("static const struct ls_rt_codepoint_range ls_rt_unicode_white_space[] = {")
    for first, last in WHITE_SPACE_RANGES:
        lines.append("    {0x%Xu, 0x%Xu}," % (first, last))
    lines.append("};")
    lines.append("")
    lines.append("static const struct ls_rt_codepoint_range ls_rt_unicode_escape[] = {")
    for first, last in escapes:
        lines.append("    {0x%Xu, 0x%Xu}," % (first, last))
    lines.append("};")
    lines.append("")
    lines.append("static bool ls_rt_unicode_in_ranges(const struct ls_rt_codepoint_range* ranges,")
    lines.append("                                    size_t count, uint32_t scalar) {")
    lines.append("    size_t low = 0;")
    lines.append("    size_t high = count;")
    lines.append("    while (low < high) {")
    lines.append("        size_t middle = low + (high - low) / 2;")
    lines.append("        if (ranges[middle].last < scalar) {")
    lines.append("            low = middle + 1;")
    lines.append("        } else {")
    lines.append("            high = middle;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return low < count && ranges[low].first <= scalar && scalar <= ranges[low].last;")
    lines.append("}")
    lines.append("")
    lines.append("static const struct ls_rt_case_entry* ls_rt_unicode_find_case(")
    lines.append("    const struct ls_rt_case_entry* entries, size_t count, uint32_t scalar) {")
    lines.append("    size_t low = 0;")
    lines.append("    size_t high = count;")
    lines.append("    while (low < high) {")
    lines.append("        size_t middle = low + (high - low) / 2;")
    lines.append("        if (entries[middle].ch < scalar) {")
    lines.append("            low = middle + 1;")
    lines.append("        } else {")
    lines.append("            high = middle;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    if (low < count && entries[low].ch == scalar) {")
    lines.append("        return &entries[low];")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    lines.append("")
    for prefix, entries, data in (
        ("upper", upper_entries, upper_data),
        ("lower", lower_entries, lower_data),
    ):
        lines.append("size_t ls_rt_unicode_%s(uint32_t scalar, uint32_t out[4]) {" % prefix)
        lines.append("    const struct ls_rt_case_entry* entry = ls_rt_unicode_find_case(")
        lines.append("        ls_rt_unicode_%s_map," % prefix)
        lines.append("        sizeof(ls_rt_unicode_%s_map) / sizeof(ls_rt_unicode_%s_map[0])," % (prefix, prefix))
        lines.append("        scalar);")
        lines.append("    size_t index;")
        lines.append("    if (entry == NULL) {")
        lines.append("        out[0] = scalar;")
        lines.append("        return 1;")
        lines.append("    }")
        lines.append("    for (index = 0; index < (size_t)entry->length; index += 1) {")
        lines.append("        out[index] = ls_rt_unicode_%s_data[entry->offset + index];" % prefix)
        lines.append("    }")
        lines.append("    return (size_t)entry->length;")
        lines.append("}")
        lines.append("")
    lines.append("bool ls_rt_unicode_is_whitespace(uint32_t scalar) {")
    lines.append("    return ls_rt_unicode_in_ranges(")
    lines.append("        ls_rt_unicode_white_space,")
    lines.append("        sizeof(ls_rt_unicode_white_space) / sizeof(ls_rt_unicode_white_space[0]),")
    lines.append("        scalar);")
    lines.append("}")
    lines.append("")
    lines.append("bool ls_rt_unicode_char_is_printable(uint32_t scalar) {")
    lines.append("    return !ls_rt_unicode_in_ranges(")
    lines.append("        ls_rt_unicode_escape,")
    lines.append("        sizeof(ls_rt_unicode_escape) / sizeof(ls_rt_unicode_escape[0]),")
    lines.append("        scalar);")
    lines.append("}")
    lines.append("")

    text = "\n".join(lines) + "\n"
    output.write_text(text, encoding="utf-8", newline="\n")

    print("wrote %s" % output)
    print("unicode version: %s" % unicodedata.unidata_version)
    print("upper mappings: %d entries, %d data scalars" % (len(upper_entries), len(upper_data)))
    print("lower mappings: %d entries, %d data scalars" % (len(lower_entries), len(lower_data)))
    print("white space ranges: %d" % len(WHITE_SPACE_RANGES))
    print("escape ranges: %d" % len(escapes))
    print("file size: %d bytes" % len(text))
    return 0


if __name__ == "__main__":
    sys.exit(main())
